// potluck: the generated project overview (R2, R4) in
// plugins/pstack/skills/grill/scripts/overview.mjs, on made-up projects.
import { afterAll, describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { build, feature, main } from "../plugins/pstack/skills/grill/scripts/overview.mjs";

const roots = [];
afterAll(() => roots.forEach((r) => rmSync(r, { recursive: true, force: true })));

const SHARED = `# Shared shopping list

Lets two people in one household keep one list and see each other's changes.

For: people who shop for the same home.

## Done when

- [x] A list shared by one person appears for the other within 5 seconds. Proof: \`npm test -- share.test.js\`
- [ ] Ticking an item off on one phone shows it ticked on the other.
- [ ] Someone who was never invited cannot open the list from its link.
`;

function project(files) {
  const root = mkdtempSync(join(tmpdir(), "potluck-overview-"));
  roots.push(root);
  for (const [rel, text] of Object.entries(files)) {
    mkdirSync(join(root, rel, ".."), { recursive: true });
    writeFileSync(join(root, rel), text);
  }
  return root;
}

describe("a feature file", () => {
  test("reads the title, summary, audience, and Done when items with their proof", () => {
    const f = feature("docs/features/shared.md", SHARED);
    expect(f.title).toBe("Shared shopping list");
    expect(f.summary).toBe("Lets two people in one household keep one list and see each other's changes.");
    expect(f.forWhom).toBe("people who shop for the same home.");
    expect(f.items).toEqual([
      { what: "A list shared by one person appears for the other within 5 seconds", done: true, proof: "`npm test -- share.test.js`" },
      { what: "Ticking an item off on one phone shows it ticked on the other", done: false, proof: null },
      { what: "Someone who was never invited cannot open the list from its link", done: false, proof: null },
    ]);
    expect(f.problems).toEqual([]);
  });

  test("a tick without proof, a plain bullet, and a missing section are errors", () => {
    expect(feature("f.md", "# F\n\n## Done when\n\n- [x] Works.\n").problems[0]).toContain("ticked without proof");
    expect(feature("f.md", "# F\n\n## Done when\n\n- Works.\n").problems[0]).toContain("must be a checkbox");
    expect(feature("f.md", "# F\n\nNothing here.\n").problems[0]).toContain('no "## Done when" section');
  });
});

describe("the overview", () => {
  test("counts progress and lists what is open, with the sources' hash in its header", () => {
    const root = project({
      "docs/features/shared.md": SHARED,
      "CONSTRAINTS.md": "# Constraints\n\n## Enforced with numbers\n\n| Dimension | Rule | Checked by | Runs at |\n|---|---|---|---|\n| Types | Zero type errors | `tsc --noEmit` | every edit |\n",
      "GLOSSARY.md": "# Glossary\n\n**List**: the items a household plans to buy.\n",
      "docs/adr/0001-sync-over-polling.md": "# Sync over polling\n",
      "docs/rulings.md": "# Rulings\n",
    });
    const { text, problems } = build(root);
    expect(problems).toEqual([]);
    expect(text).toMatch(/^<!-- Generated by potluck's grill\/scripts\/overview\.mjs .* sources: [0-9a-f]{16} -->\n/);
    expect(text).toContain("1 feature; 1 of 3 done conditions met with proof.");
    expect(text).toContain("| [Shared shopping list](features/shared.md) | people who shop for the same home. | 1 of 3 | 2 |");
    expect(text).toContain("- [x] A list shared by one person appears for the other within 5 seconds (proof: `npm test -- share.test.js`)");
    expect(text).toContain("- [ ] Someone who was never invited cannot open the list from its link");
    expect(text).toContain("- Types: Zero type errors (checked by `tsc --noEmit`)");
    expect(text).toContain("- [Sync over polling](adr/0001-sync-over-polling.md)");
    expect(text).toContain("## Terms\n\nList");
  });

  test("--check fails until --write, then passes, and fails again when a source changes", () => {
    const root = project({ "docs/features/shared.md": SHARED });
    expect(main(["--root", root, "--check"])).toBe(1);
    expect(main(["--root", root, "--write"])).toBe(0);
    expect(main(["--root", root, "--check"])).toBe(0);
    writeFileSync(join(root, "docs/features/shared.md"), SHARED.replace("- [ ] Ticking", "- [x] Ticking").replace("on the other.\n", "on the other. Proof: manual check in two browsers\n"));
    expect(main(["--root", root, "--check"])).toBe(1);
    expect(main(["--root", root, "--write"])).toBe(0);
    expect(readFileSync(join(root, "docs/overview.md"), "utf8")).toContain("2 of 3 done conditions met with proof.");
  });

  test("a tick without proof fails --write and --check alike", () => {
    const root = project({ "docs/features/f.md": "# F\n\n## Done when\n\n- [x] Works.\n" });
    expect(main(["--root", root, "--write"])).toBe(1);
    expect(main(["--root", root, "--check"])).toBe(1);
  });

  test("a project with none of the sources needs no overview", () => {
    expect(main(["--root", project({ "README.md": "# Hi\n" }), "--check"])).toBe(0);
    expect(main(["--write", "--check"])).toBe(2);
  });
});

describe("scope and parsing", () => {
  test("a project with only CONSTRAINTS.md or an ADR needs no overview, but a leftover overview fails", () => {
    expect(main(["--root", project({ "CONSTRAINTS.md": "# Constraints\n" }), "--check"])).toBe(0);
    expect(main(["--root", project({ "docs/adr/0001-x.md": "# X\n" }), "--check"])).toBe(0);
    expect(main(["--root", project({ "docs/overview.md": "old\n", "GLOSSARY.md": "# G\n" }), "--check"])).toBe(1);
  });

  test("the summary comes only from before the first section, so another section's ticks never render", () => {
    const f = feature("f.md", "# F\n\n## Notes\n\n- [x] migrated the db\n\n## Done when\n\n- [ ] Works.\n");
    expect(f.summary).toBe("");
    expect(f.items).toEqual([{ what: "Works", done: false, proof: null }]);
  });

  test("numbered and plus checkboxes, a bold For:, a BOM, and 'Done when:' all parse", () => {
    const f = feature("f.md", "\uFEFF# F\n\nIntro.\n\n**For:** clubs\n\n## Done when:\n\n1. [x] One. Proof: test a\n+ [ ] Two\n".replace(/^\uFEFF/, ""));
    expect(f.title).toBe("F");
    expect(f.forWhom).toBe("clubs");
    expect(f.items.map((i) => i.done)).toEqual([true, false]);
    const root = project({ "docs/features/a.md": "\uFEFF# Bom\n\n## Done when\n\n- [ ] x\n" });
    expect(build(root).text).toContain("[Bom](features/a.md)");
  });

  test("a .markdown feature counts, a folder in docs/features is an error, not a crash", () => {
    const root = project({ "docs/features/a.markdown": "# A\n\n## Done when\n\n- [ ] x\n", "docs/features/sub/b.md": "# B\n" });
    const { text, problems } = build(root);
    expect(problems).toEqual(["docs/features/sub: put each feature in its own .md file directly in docs/features/"]);
    expect(text).toContain("[A](features/a.markdown)");
  });

  test("a feature with no Done when items is an error", () => {
    expect(feature("f.md", "# F\n\n## Done when\n\nNothing yet.\n").problems[0]).toContain("has no items");
  });

  test("pipes and spaces are escaped in the table and links, and CONSTRAINTS cells keep escaped pipes", () => {
    const root = project({
      "docs/features/share list (v2).md": "# A | B\n\n## Done when\n\n- [ ] x\n",
      "CONSTRAINTS.md": "## Enforced with numbers\n\n| Dimension | Rule | Checked by |\n|---|---|---|\n| Lint | none | `a \\| b` |\n| Empty |  | `x` |\n",
    });
    const { text } = build(root);
    expect(text).toContain("| [A \\| B](<features/share list (v2).md>) |");
    expect(text).toContain("- Lint: none (checked by `a \\| b`)");
    expect(text).toContain("- Empty:  (checked by `x`)");
  });

  test("the README says what the project is", () => {
    const root = project({ "README.md": "# Bookclub\n\nVotes for the next book.\n", "docs/features/a.md": "# A\n\n## Done when\n\n- [ ] x\n" });
    const { text } = build(root);
    expect(text).toContain("# Bookclub: overview\n\nVotes for the next book.\n");
  });

  test("the overview is the same for CRLF sources, sorts features by name, and changes when a file is renamed", () => {
    const lf = project({ "docs/features/b.md": "# B\n\n## Done when\n\n- [ ] x\n", "docs/features/a.md": "# A\n\n## Done when\n\n- [ ] y\n" });
    const crlf = project({ "docs/features/b.md": "# B\r\n\r\n## Done when\r\n\r\n- [ ] x\r\n", "docs/features/a.md": "# A\r\n\r\n## Done when\r\n\r\n- [ ] y\r\n" });
    expect(build(crlf).text).toBe(build(lf).text);
    const text = build(lf).text;
    expect(text.indexOf("[A]")).toBeLessThan(text.indexOf("[B]"));
    const renamed = project({ "docs/features/c.md": "# B\n\n## Done when\n\n- [ ] x\n", "docs/features/a.md": "# A\n\n## Done when\n\n- [ ] y\n" });
    expect(build(renamed).text.split("\n")[0]).not.toBe(text.split("\n")[0]);
  });
});

describe("files that are not features", () => {
  test("a .DS_Store and a README.md index in docs/features are skipped", () => {
    const root = project({ "docs/features/.DS_Store": "\0\0", "docs/features/README.md": "# Features\n", "docs/features/a.md": "# A\n\n## Done when\n\n- [ ] x\n" });
    const { text, problems } = build(root);
    expect(problems).toEqual([]);
    expect(text).toContain("1 feature;");
  });

  test("features only in a subfolder are an error, not a silent pass", () => {
    const root = project({ "docs/features/sub/a.md": "# A\n\n## Done when\n\n- [ ] x\n" });
    expect(main(["--root", root, "--check"])).toBe(1);
  });

  test("a README change outside its title and first paragraph leaves the overview current", () => {
    const root = project({ "README.md": "# Club\n\nVotes.\n\n## Install\n\nnpm i\n", "docs/features/a.md": "# A\n\n## Done when\n\n- [ ] x\n" });
    expect(main(["--root", root, "--write"])).toBe(0);
    writeFileSync(join(root, "README.md"), "# Club\n\nVotes.\n\n## Install\n\nnpm install\n");
    expect(main(["--root", root, "--check"])).toBe(0);
    writeFileSync(join(root, "README.md"), "# Club\n\nVotes on books.\n");
    expect(main(["--root", root, "--check"])).toBe(1);
  });
});

test("a wrapped README paragraph shows whole, and a language switcher is not the description", () => {
  const root = project({ "README.md": "# Club\n\n**English** | [中文](README.zh-CN.md)\n\nLine one of about\ncontinues here.\n", "docs/features/a.md": "# A\n\n## Done when\n\n- [ ] x\n" });
  expect(build(root).text).toContain("# Club: overview\n\nLine one of about\ncontinues here.\n\n1 feature;");
});
